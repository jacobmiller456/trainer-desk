const { chromium } = require('playwright');
const path = require('path');
(async()=>{
  const b = await chromium.launch(); const page = await b.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const cors={'access-control-allow-origin':'*'};
  let cardReqs=0, setReqs=0;
  await page.route('**/*', r=>{
    const u=r.request().url();
    if(u.startsWith('https://api.pokemontcg.io/v2/sets')) setReqs++;
    if(u.startsWith('https://api.pokemontcg.io/v2/cards')) cardReqs++;
    if(u.startsWith('file://')) return r.continue();
    if(u.startsWith('https://api.pokemontcg.io/v2/sets')) return r.fulfill({status:200,headers:cors,contentType:'application/json',body:JSON.stringify({data:[{id:'liv1',name:'Live Set One',releaseDate:'2025/01/01'},{id:'liv2',name:'Live Set Two',releaseDate:'2024/01/01'}]})});
    if(u.startsWith('https://api.pokemontcg.io/v2/cards')) return r.fulfill({status:200,headers:cors,contentType:'application/json',body:JSON.stringify({data:[{id:'a',name:'Live Card A',number:'1',rarity:'Rare',tcgplayer:{updatedAt:'2026/10/10',prices:{normal:{low:1},holofoil:{market:12.5}}},images:{small:'data:image/gif;base64,R0lGODlhAQABAAAAACw='}},{id:'b',name:'Live Card B',number:'2',rarity:'Common',cardmarket:{updatedAt:'2026/10/10',prices:{trendPrice:0.4}},images:{small:'data:image/gif;base64,R0lGODlhAQABAAAAACw='}}]})});
    return r.abort();
  });
  await page.goto('file://'+path.resolve(process.argv[2]));
  await page.click('button[data-view="tcg"]');
  await page.waitForFunction(()=>document.querySelectorAll('#card-grid .tcard').length===2,null,{timeout:8000});
  const status=await page.textContent('#tcg-status');
  const opts=await page.$$eval('#set-select option',o=>o.map(x=>x.textContent));
  const names=await page.$$eval('#card-grid .nm',n=>n.map(x=>x.textContent));
  console.log({status,opts,names,errors});
  const prices=await page.$$eval('#card-grid .price',n=>n.map(x=>x.textContent));
  console.log({prices});
  const ok=prices.join('|')==='$12.50TCGplayer|€0.40Cardmarket'&&status==='2 cards'&&opts.length===2&&names[0]==='Live Card A'&&!errors.length;
  console.log(ok?'PASS tcg live path':'FAIL tcg live path');
  // cache: switching sets and back, then reloading, must not refetch what was already loaded
  await page.selectOption('#set-select','liv2');
  await page.waitForFunction(()=>document.querySelector('#tcg-status').textContent==='2 cards');
  await page.selectOption('#set-select','liv1');
  await page.waitForFunction(()=>document.querySelectorAll('#card-grid .tcard').length===2);
  const afterSwitch={cardReqs,setReqs};
  await page.reload(); await page.click('button[data-view="tcg"]');
  await page.waitForFunction(()=>document.querySelectorAll('#card-grid .tcard').length===2);
  const cacheOk=afterSwitch.cardReqs===2&&afterSwitch.setReqs===1&&cardReqs===2&&setReqs===1&&!errors.length;
  console.log({afterSwitch,cardReqs,setReqs});
  console.log(cacheOk?'PASS tcg cache (1 request per set, none on revisit/reload)':'FAIL tcg cache');
  await b.close(); process.exit(ok&&cacheOk?0:1);
})();
